/**
 * Build a map from translated labels (in all supported languages) to body part IDs.
 * This allows matching user input in any language to the correct body part.
 */
export function buildLabelToIdMap(): Record<string, BodyPartId> {
  const map: Record<string, BodyPartId> = {};
  const allLocales = [enLocale.bodyMap, deLocale.bodyMap];

  BODY_PART_IDS.forEach(key => {
    allLocales.forEach(locale => {
      const translation = locale[key as keyof typeof locale];
      if (translation) {
        // Store both original case and lowercase for flexible matching
        map[translation] = key;
        map[translation.toLowerCase()] = key;
      }
    });
    // Also add the ID itself for direct matching
    map[key] = key;
    map[key.toLowerCase()] = key;
  });

  return map;
}

// Pre-built label to ID map (created once at module load)
export const LABEL_TO_ID_MAP = buildLabelToIdMap();

/**
 * Find body part ID from a location string (supports any language).
 * Returns null if no match found.
 */
export function findBodyPartIdFromLocation(location: string): BodyPartId | null {
  if (!location) return null;
  
  const trimmedLoc = location.trim();
  
  // Direct match (exact or lowercase)
  if (LABEL_TO_ID_MAP[trimmedLoc]) return LABEL_TO_ID_MAP[trimmedLoc];
  if (LABEL_TO_ID_MAP[trimmedLoc.toLowerCase()]) return LABEL_TO_ID_MAP[trimmedLoc.toLowerCase()];
  
  // Case-insensitive substring search (find if location contains a body part name)
  const locLower = trimmedLoc.toLowerCase();
  for (const [label, id] of Object.entries(LABEL_TO_ID_MAP)) {
    if (locLower.includes(label.toLowerCase()) && label.length > 2) {
      return id;
    }
  }
  
  return null;
}
